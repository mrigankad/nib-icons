"""Generate packages/react from icons.json. Run: python -I scripts/build_react.py"""
import json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "packages" / "react"
SRC = OUT / "src"

TAG_RE = re.compile(r"<(\w+)((?:\s+[\w:-]+=\"[^\"]*\")*)\s*/?>")
ATTR_RE = re.compile(r"([\w:-]+)=\"([^\"]*)\"")


def camel(a):
    return re.sub(r"[-:](\w)", lambda m: m.group(1).upper(), a)


def pascal(n):
    return "Nib" + "".join(p[:1].upper() + p[1:] for p in n.split("-"))


def children(svg):
    out = []
    for m in TAG_RE.finditer(svg):
        attrs = []
        for k, v in ATTR_RE.findall(m.group(2)):
            if (k, v) in (("stroke", "currentColor"), ("stroke-width", "1.5"), ("stroke-linecap", "round"), ("stroke-linejoin", "round")):
                continue  # inherited from the root <svg> so size/color/strokeWidth props apply
            attrs.append((camel(k), v))
        props = ", ".join(f"{k}: {json.dumps(v)}" for k, v in attrs)
        out.append(f"h('{m.group(1)}', {{ {props} }})")
    return out


def main():
    icons = json.loads((ROOT / "icons.json").read_text(encoding="utf-8"))
    if SRC.exists():
        shutil.rmtree(SRC)
    SRC.mkdir(parents=True)
    names, seen = [], set()
    for ic in icons:
        p = pascal(ic["name"])
        while p.lower() in seen:  # case-insensitive filesystems (Windows, macOS) would merge the files
            p += "Alt"
        seen.add(p.lower())
        names.append(p)
        kids = children(ic["svg"])
        body = ",\n    ".join(kids)
        js = f"""import {{ createElement as h, forwardRef }} from 'react';

export const {p} = forwardRef(function {p}({{ size = 24, color = 'currentColor', strokeWidth = 1.5, ...props }}, ref) {{
  return h(
    'svg',
    {{ ref, xmlns: 'http://www.w3.org/2000/svg', viewBox: '0 0 24 24', width: size, height: size, fill: 'none', stroke: color, strokeWidth, strokeLinecap: 'round', strokeLinejoin: 'round', ...props }},
    {body}
  );
}});

export default {p};
"""
        (SRC / f"{p}.js").write_text(js, encoding="utf-8", newline="\n")
    (SRC / "index.js").write_text(
        "".join(f"export {{ {n} }} from './{n}.js';\n" for n in names), encoding="utf-8", newline="\n")
    dts = ("import * as React from 'react';\n\n"
           "export type NibProps = React.SVGProps<SVGSVGElement> & { size?: number | string; color?: string; strokeWidth?: number | string };\n"
           "export type NibIcon = React.ForwardRefExoticComponent<NibProps & React.RefAttributes<SVGSVGElement>>;\n\n"
           + "".join(f"export const {n}: NibIcon;\n" for n in names))
    (SRC / "index.d.ts").write_text(dts, encoding="utf-8", newline="\n")
    (OUT / "index.d.ts").write_text("export * from './src/index';\n", encoding="utf-8", newline="\n")
    pkg = {
        "name": "nib-icons-react", "version": "1.1.0", "description": "Nib icon set as React components",
        "type": "module", "main": "src/index.js", "module": "src/index.js", "types": "index.d.ts",
        "sideEffects": False, "files": ["src", "index.d.ts"],
        "peerDependencies": {"react": ">=17"}, "license": "MIT",
        "repository": {"type": "git", "url": "git+https://github.com/mrigankad/nib-icons.git", "directory": "packages/react"},
    }
    if not (OUT / "package.json").exists(): (OUT / "package.json").write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8", newline="\n")
    if not (OUT / "README.md").exists(): (OUT / "README.md").write_text(f"""# nib-icons-react

{len(names)} Nib icons as React components. No JSX, no build step (plain `React.createElement`).

**Not yet published to npm.** Until it is, copy the component(s) you need.

## Use (copy)

Copy `packages/react/src/NibHome.js` from the repo into your project:

```jsx
import {{ NibHome }} from './NibHome.js';

<NibHome size={{20}} />
<NibHome size={{32}} color="#d32704" strokeWidth={{2}} />
```

Each file only imports `react`, so it works in any React >=17 project.

## Use (once published)

```sh
npm i nib-icons-react
```

```jsx
import {{ NibHome }} from 'nib-icons-react';
```

Props: `size` (default 24), `color` (default `currentColor`), `strokeWidth` (default 1.5), plus any SVG props and a `ref`.

MIT licensed. Generated by `scripts/build_react.py`.
""", encoding="utf-8", newline="\n")
    print(len(names), "components")


main()
